/** A globally installed clawbridge-codex 2.11.4 running from ~/.clawbridge, like the real thing. */
function codexInstall(home: string) {
  const cb = path.join(home, '.clawbridge');
  const oldPkg = fakePackage(path.join(home, 'npm', 'node_modules', 'clawbridge-codex'), 'clawbridge-codex');
  const runtime = fakePackage(path.join(cb, 'runtime', 'clawbridge-codex-2.11.4'), 'clawbridge-codex');
  const aiPkg = fakePackage(path.join(home, 'npm', 'node_modules', 'clawbridge-ai'), 'clawbridge-ai', '3.0.0');
  for (const g of ['main', 'analyst', 'global']) fs.mkdirSync(path.join(cb, 'groups', g), { recursive: true });
  fs.writeFileSync(path.join(cb, 'groups', 'main', 'CLAUDE.local.md'), 'be nice\n');
  fs.writeFileSync(
    path.join(cb, 'groups', 'analyst', 'container.json'),
    JSON.stringify({ imageTag: 'clawbridge-codex-v2-2ce56563:ag-analyst', packages: { apt: ['jq'], npm: [] } }),
  );
  fs.mkdirSync(path.join(cb, 'src'), { recursive: true });
  fs.writeFileSync(path.join(cb, '.env'), CODEX_ENV);
  fs.symlinkSync(path.join(runtime, 'container'), path.join(cb, 'container'));
  fs.symlinkSync(path.join(oldPkg, 'dist', 'shared'), path.join(cb, 'src', 'shared'));
  fs.symlinkSync(path.join(oldPkg, 'integrations', 'docker-compose.yml'), path.join(cb, 'docker-compose.yml'));
  const db = fakeDb(path.join(cb, 'data', 'v2.db'), ['main', 'analyst']);
  const sessDir = path.join(cb, 'data', 'v2-sessions', 'ag-1', 'sess-1');
  fs.mkdirSync(sessDir, { recursive: true });
  const sess = new Database(path.join(sessDir, 'inbound.db'));
  sess.exec('CREATE TABLE messages_in (id TEXT)');
  sess.close();
  // A non-SQLite file with a .db name must not break the backup.
  fs.writeFileSync(path.join(cb, 'data', 'notes.db'), 'not sqlite');
  const agents = path.join(home, 'Library', 'LaunchAgents');
  fs.mkdirSync(agents, { recursive: true });
  const plistFile = path.join(agents, 'com.clawbridge-v2-2ce56563.plist');
  fs.writeFileSync(
    plistFile,
    plist(
      'com.clawbridge-v2-2ce56563',
      ['/opt/homebrew/bin/node', path.join(runtime, 'dist', 'docker-gate.js'), path.join(runtime, 'dist', 'index.js')],
      cb,
      'clawbridge-codex-v2-2ce56563:latest',
    ),
  );
  return { cb, oldPkg, runtime, aiPkg, db, plistFile };
}

/**
 * Records service-manager calls and answers state queries the way launchd and
 * systemd do: `launchctl print` exits 0 (loaded) or 113 (not found);
 * `systemctl show -p ActiveState` prints active or inactive. Labels in
 * `stillRunning` stay running; labels in `unknown` give no usable answer.
 */
function recorder(stillRunning: string[] = [], unknown: string[] = []) {
  const calls: string[] = [];
  return {
    calls,
    run: (cmd: string, args: string[]) => {
      calls.push([cmd, ...args].join(' '));
      const line = args.join(' ');
      const running = stillRunning.some((l) => line.includes(l));
      if (unknown.some((l) => line.includes(l)) && (args.includes('print') || args.includes('show'))) {
        return { status: 1, stdout: '' };
      }
      if (args.includes('print')) return { status: running ? 0 : 113 };
      if (args.includes('show')) return { status: 0, stdout: running ? 'active\n' : 'inactive\n' };
      return { status: 0 };
    },
  };
}

const darwin = (home: string) => ({ home, platform: 'darwin' as const, isAlive: () => false });

function aiPlist(home: string, aiPkg: string, cb: string): string {
  const file = path.join(home, 'Library', 'LaunchAgents', 'com.clawbridge-v2-new.plist');
  fs.writeFileSync(file, plist('com.clawbridge-v2-new', ['/bin/node', path.join(aiPkg, 'dist', 'index.js')], cb));
  return file;
}

