function tmpHome(): string {
  return fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'cb-legacy-')));
}

/** A package root with the files ~/.clawbridge links into. */
function fakePackage(root: string, name: string, version = '2.11.4'): string {
  fs.mkdirSync(path.join(root, 'dist', 'shared'), { recursive: true });
  fs.mkdirSync(path.join(root, 'container', 'agent-runner', 'src'), { recursive: true });
  fs.mkdirSync(path.join(root, 'integrations'), { recursive: true });
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name, version }));
  fs.writeFileSync(path.join(root, 'dist', 'index.js'), '');
  fs.writeFileSync(path.join(root, 'integrations', 'docker-compose.yml'), 'services: {}\n');
  return root;
}

/** A central DB in WAL mode; rows inserted later sit in the WAL until checkpoint. */
function fakeDb(file: string, groups: string[]): Database.Database {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const db = new Database(file);
  db.pragma('journal_mode = WAL');
  db.pragma('wal_autocheckpoint = 0');
  db.exec('CREATE TABLE agent_groups (id TEXT PRIMARY KEY, name TEXT)');
  db.exec('CREATE TABLE schema_version (version INTEGER PRIMARY KEY, name TEXT NOT NULL, applied TEXT NOT NULL)');
  const ins = db.prepare('INSERT INTO agent_groups VALUES (?, ?)');
  for (const g of groups) ins.run(g, g);
  return db;
}

function plist(label: string, args: string[], workDir: string, image?: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0"><dict>
  <key>Label</key><string>${label}</string>
  <key>ProgramArguments</key><array>${args.map((a) => `<string>${a}</string>`).join('')}</array>
  <key>EnvironmentVariables</key><dict>
    ${image ? `<key>CONTAINER_IMAGE</key><string>${image}</string>` : ''}
    <key>HOME</key><string>/Users/x</string>
  </dict>
  <key>WorkingDirectory</key><string>${workDir}</string>
</dict></plist>
`;
}

